#include <iostream>
using namespace std;

int main() {
    setlocale(LC_ALL, "Russian");

    int direction; // Код направления

    // Запрашиваем код направления у пользователя
    cout << "Введите код направления (1-4): ";
    cin >> direction;

    // Выбираем направление с помощью switch
    switch (direction) {
    case 1:
        // Код 1 соответствует северу
        cout << "Направление: Север" << endl;
        break;

    case 2:
        // Код 2 соответствует югу
        cout << "Направление: Юг" << endl;
        break;

    case 3:
        // Код 3 соответствует западу
        cout << "Направление: Запад" << endl;
        break;

    case 4:
        // Код 4 соответствует востоку
        cout << "Направление: Восток" << endl;
        break;

    default:
        // Обрабатываем неверный код направления
        cout << "Ошибка: введите число от 1 до 4!" << endl;
        break;
    }

    return 0;
}